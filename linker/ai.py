"""LLM assist layer (optional) — the 'reads and explains' part.

Given a new incident and the matches the offline engine already found, this asks
a locally-running LLM (via Ollama) to write a short, plain-English linkage
assessment: which past incidents it most resembles and why, phrased the way an
analyst would brief it. The LLM is *only* handed structured facts the pipeline
extracted plus the match scores — it summarises and explains, it does not
invent evidence.

This layer is entirely optional and fully offline. If Ollama isn't running or
the model isn't pulled, `available()` returns False and the web app simply
hides the AI panel and shows the offline results — nothing breaks.

Setup (one time):
    curl -fsSL https://ollama.com/install.sh | sh
    ollama pull qwen2.5:7b
"""
from __future__ import annotations

import requests

OLLAMA_URL = "http://127.0.0.1:11434"
DEFAULT_MODEL = "qwen2.5:7b"

_SYSTEM = (
    "You are a decision-support assistant for counter-IED incident analysts. "
    "You are given a NEW incident and FACT sentences about PAST incidents, "
    "already generated by code and guaranteed accurate.\n\n"
    "STRICT RULES — follow exactly:\n"
    "1. Do NOT list, restate, or describe which specific feature or entity a "
    "specific past incident shares — the analyst already sees an exact table "
    "of that below your text, and any rewording risks small errors. Instead, "
    "refer the reader to it (e.g. \"see the shared-feature list below\").\n"
    "2. You MAY name incident ids and their confidence band (weak/medium/"
    "strong) exactly as given, and give a general, high-level sense of the "
    "pattern (e.g. \"most matches involve corroded mortar rounds and command "
    "wires, but none reach a strong confidence band\").\n"
    "3. State plainly whether ANY match has a shared entity (person/group/"
    "phone) at all, without naming which specific past incident it belongs "
    "to unless a FACT sentence explicitly says \"shares identity\" for it.\n"
    "4. Never claim a person, group, or phone number connects to a past "
    "incident unless that incident's own FACT sentence says so.\n"
    "5. Do not introduce any name, number, or feature not present in the "
    "facts given.\n"
    "6. Do not write closing reminders, disclaimers, or meta-instructions — "
    "write only the assessment prose itself, nothing else.\n\n"
    "Write 3-5 sentences (80-120 words), plain English: an overall read of "
    "whether this incident fits a known pattern, which 1-2 incident ids are "
    "the closest matches and their band, and whether any identity overlap "
    "exists at all — without restating specific feature/entity details "
    "yourself."
)

_AREA_SYSTEM = (
    "You are a decision-support assistant writing a pre-arrival briefing for "
    "a field responder about to visit a specific area. You are given FACT "
    "sentences about that area's past reporting, already generated by code "
    "and guaranteed accurate.\n\n"
    "STRICT RULES — follow exactly:\n"
    "1. Do NOT list, restate, or invent specific counts, object types, or "
    "shared features yourself — the responder already sees exact tables of "
    "that below your text. Refer to them only in general terms (e.g. "
    "\"several mortar rounds have been reported here\") without inventing "
    "numbers not in the facts given.\n"
    "2. Do NOT identify what the responder is currently looking at, and do "
    "NOT give any handling, defusing, disarming, moving, or render-safe "
    "guidance of any kind — this is retrieval of past reporting only.\n"
    "3. Do not introduce any place name, object type, or number not present "
    "in the facts given.\n"
    "4. Do not write closing reminders, disclaimers, or meta-instructions — "
    "write only the briefing prose itself, nothing else.\n\n"
    "Write 3-5 sentences (80-120 words), plain English: a general orientation "
    "to what this area's history looks like and how confidently any "
    "description match relates to it — without restating exact figures or "
    "feature lists yourself."
)


def available() -> tuple[bool, str]:
    """(is_available, human-readable reason)."""
    try:
        resp = requests.get(f"{OLLAMA_URL}/api/tags", timeout=2)
        resp.raise_for_status()
    except Exception:
        return False, "Ollama isn't running (start it with 'ollama serve' or check the systemd service)."
    names = {m.get("name", "") for m in resp.json().get("models", [])}
    if not any(n.startswith(DEFAULT_MODEL.split(":")[0]) for n in names):
        return False, f"Model '{DEFAULT_MODEL}' not pulled yet (run: ollama pull {DEFAULT_MODEL})."
    return True, "ready"


def _fmt_incident(inc) -> str:
    feats = ", ".join(f"{f.facet}={f.value}" for f in inc.features) or "none"
    ents = []
    if inc.persons: ents.append("persons: " + ", ".join(sorted(inc.persons)))
    if inc.groups:  ents.append("groups: " + ", ".join(sorted(inc.groups)))
    if inc.phones:  ents.append("phones: " + ", ".join(sorted(inc.phones)))
    ent_str = "; ".join(ents) or "none"
    return (f"id={inc.incident_id} | date={inc.date or '?'} | "
            f"location={inc.location or '?'}\n  features: {feats}\n  entities: {ent_str}\n"
            f"  narrative: {inc.narrative.strip()[:600]}")


def _score_band(x: float) -> str:
    return "strong" if x >= 0.66 else "medium" if x >= 0.40 else "weak"


def _structured_fact_sentence(inc, link) -> str:
    """Pre-render a guaranteed-accurate sentence for one structured match.
    The LLM is instructed to use these near-verbatim rather than reconstruct
    the shared-feature/entity lists itself, closing off a whole class of
    small model hallucination."""
    band = _score_band(link.score)
    feats = ", ".join(link.shared_features) if link.shared_features else None
    ents = ", ".join(link.shared_entities) if link.shared_entities else None
    bits = []
    if feats:
        bits.append(f"shares {feats}")
    if ents:
        bits.append(f"shares identity: {ents}")
    if not bits:
        bits.append("shares only a general similarity, no specific feature or entity overlap")
    where = f" in {inc.location}" if inc.location else ""
    return (f"FACT: {inc.incident_id}{where} is a {band} structured match "
            f"(score {link.score:.2f}) with the new incident — it {', and it '.join(bits)}.")


def _semantic_fact_sentence(inc, sim) -> str:
    band = _score_band(sim)
    snippet = inc.narrative.strip()[:140]
    where = f" in {inc.location}" if inc.location else ""
    return (f"FACT: {inc.incident_id}{where} is a {band} meaning/text match "
            f"(similarity {sim:.2f}); its narrative begins: \"{snippet}...\"")


def _build_context(new_inc, structured, semantic) -> str:
    lines = ["=== NEW INCIDENT ===", _fmt_incident(new_inc), "",
             "=== STRUCTURED MATCH FACTS (use these near-verbatim) ==="]
    if structured:
        for inc, link in structured:
            lines.append(_structured_fact_sentence(inc, link))
    else:
        lines.append("(no structured matches above threshold)")
    lines += ["", "=== MEANING MATCH FACTS (use these near-verbatim) ==="]
    if semantic:
        for inc, sim in semantic:
            lines.append(_semantic_fact_sentence(inc, sim))
    else:
        lines.append("(no meaning matches)")
    return "\n".join(lines)


def assess(new_inc, structured, semantic, model: str = DEFAULT_MODEL) -> dict:
    """Return {'ok': bool, 'text': str|None, 'reason': str, 'model': str}."""
    ok, reason = available()
    if not ok:
        return {"ok": False, "text": None, "reason": reason, "model": model}
    try:
        context = _build_context(new_inc, structured, semantic)
        resp = requests.post(
            f"{OLLAMA_URL}/api/chat",
            json={
                "model": model,
                "messages": [
                    {"role": "system", "content": _SYSTEM},
                    {"role": "user", "content":
                        f"Assess the linkage for this new incident.\n\n{context}"},
                ],
                "stream": False,
            },
            timeout=90,
        )
        resp.raise_for_status()
        text = resp.json().get("message", {}).get("content", "").strip()
        if not text:
            return {"ok": False, "text": None, "reason": "Empty response from model", "model": model}
        # Reminder is appended by code, not the LLM, so it can never be
        # garbled, echoed as a meta-instruction, or omitted.
        text = text.rstrip()
        if not text.endswith("."):
            text += "."
        text += " A human analyst confirms any link before acting on it."
        return {"ok": True, "text": text, "reason": "ok", "model": model}
    except Exception as e:  # network, timeout, bad model — never crash the app
        return {"ok": False, "text": None,
                "reason": f"Local LLM call failed: {type(e).__name__}: {e}", "model": model}


def _area_fact_sentences(brief) -> str:
    """Pre-render guaranteed-accurate facts about an area brief. Same
    anti-hallucination approach as _structured_fact_sentence: the LLM is
    only shown facts it cannot get wrong, and is told to summarise rather
    than restate them."""
    lines = [f"FACT: area queried = {brief.location_query}.",
             f"FACT: {brief.n_in_area} incident(s) on record in this area."]

    if brief.object_profile:
        top = brief.object_profile[:5]
        obj_list = "; ".join(f"{t} (seen {c}x, most recent {r or 'unknown'})"
                             for t, c, r in top)
        lines.append(f"FACT: object types reported in this area: {obj_list}.")
    else:
        lines.append("FACT: no object-type reporting on record for this area.")

    if brief.area_signature:
        lines.append(f"FACT: this area's common device signature: "
                     f"{', '.join(brief.area_signature)}.")
    else:
        lines.append("FACT: no dominant shared device signature for this area.")

    if brief.describe_query:
        lines.append(f"FACT: responder description on file: \"{brief.describe_query}\".")
        if brief.matches:
            for m in brief.matches[:3]:
                band = _score_band(m.score)
                shared = ", ".join(m.shared) if m.shared else "no specific shared features"
                lines.append(f"FACT: closest match {m.incident_id} ({band}, "
                             f"score {m.score:.2f}) — {shared}.")
        else:
            lines.append("FACT: no past record closely matched the description.")

    return "\n".join(lines)


def assess_area(brief, model: str = DEFAULT_MODEL) -> dict:
    """Return {'ok': bool, 'text': str|None, 'reason': str, 'model': str}
    for a pre-arrival area briefing. Same grounded fact-sentence approach
    as assess() — never invents figures, never gives handling guidance."""
    ok, reason = available()
    if not ok:
        return {"ok": False, "text": None, "reason": reason, "model": model}
    try:
        context = _area_fact_sentences(brief)
        resp = requests.post(
            f"{OLLAMA_URL}/api/chat",
            json={
                "model": model,
                "messages": [
                    {"role": "system", "content": _AREA_SYSTEM},
                    {"role": "user", "content":
                        f"Write the pre-arrival briefing for this area.\n\n{context}"},
                ],
                "stream": False,
            },
            timeout=90,
        )
        resp.raise_for_status()
        text = resp.json().get("message", {}).get("content", "").strip()
        if not text:
            return {"ok": False, "text": None, "reason": "Empty response from model", "model": model}
        text = text.rstrip()
        if not text.endswith("."):
            text += "."
        text += (" This is retrieval from past reporting only, not identification "
                 "of the present object — a qualified specialist confirms all IDs.")
        return {"ok": True, "text": text, "reason": "ok", "model": model}
    except Exception as e:
        return {"ok": False, "text": None,
                "reason": f"Local LLM call failed: {type(e).__name__}: {e}", "model": model}
